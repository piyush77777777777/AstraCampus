export function runScheduleValidator(sessions = CIT_SCHEDULED_SESSIONS, bookings = CIT_SPECTRA_BOOKINGS, exams = CIT_MIDSEM_EXAMS) {
  const violations = [];
  const softPenalties = [];

  // 1. Incomplete sessions
  sessions.forEach(s => {
    if (!s.day || !s.startPeriod || !s.roomId) {
      violations.push({ type: 'INCOMPLETE_SESSION', message: `Session ${s.id} missing day, period or room.` });
    }
  });

  // 2. Room double bookings
  const roomSlots = {};
  sessions.forEach(s => {
    const key = `${s.roomId}_${s.day}_${s.startPeriod}`;
    if (roomSlots[key]) {
      violations.push({ type: 'ROOM_CLASH', message: `Room ${s.roomId} double booked at ${s.day} ${s.startPeriod}` });
    } else {
      roomSlots[key] = s;
    }
  });

  // 3. Faculty double bookings
  const facSlots = {};
  sessions.forEach(s => {
    const key = `${s.facultyId}_${s.day}_${s.startPeriod}`;
    if (facSlots[key]) {
      violations.push({ type: 'FACULTY_CLASH', message: `Faculty ${s.facultyName} double booked at ${s.day} ${s.startPeriod}` });
    } else {
      facSlots[key] = s;
    }
  });

  // 4. Student group double bookings
  const grpSlots = {};
  sessions.forEach(s => {
    const key = `${s.studentGroupId}_${s.day}_${s.startPeriod}`;
    if (grpSlots[key]) {
      violations.push({ type: 'GROUP_CLASH', message: `Group ${s.studentGroupId} overlapping at ${s.day} ${s.startPeriod}` });
    } else {
      grpSlots[key] = s;
    }
  });

  // 5. Room capacity check
  sessions.forEach(s => {
    const r = CIT_ROOMS.find(room => room.id === s.roomId);
    const g = CIT_STUDENT_GROUPS.find(grp => grp.id === s.studentGroupId);
    if (r && g && r.capacity < g.size) {
      violations.push({ type: 'CAPACITY_OVERFLOW', message: `Room ${r.name} (${r.capacity}) less than group ${g.name} (${g.size})` });
    }
  });

  // 6. Lab room type check
  sessions.forEach(s => {
    if (s.isLab && s.roomType) {
      const r = CIT_ROOMS.find(room => room.id === s.roomId);
      if (r && r.type !== s.roomType) {
        violations.push({ type: 'ROOM_TYPE_MISMATCH', message: `Lab ${s.courseName} needs ${s.roomType} but scheduled in ${r.type}` });
      }
    }
  });

  // 7. Lunch violation check
  sessions.forEach(s => {
    if (s.startPeriod === 'LUNCH' || (s.isLab && s.startPeriod === 'P4')) {
      violations.push({ type: 'LUNCH_VIOLATION', message: `Session ${s.id} runs into Lunch Break (13:00 - 14:00)` });
    }
  });

  // 8. Faculty daily limit <= 4 hours
  const facDailyHours = {};
  sessions.forEach(s => {
    const key = `${s.facultyId}_${s.day}`;
    facDailyHours[key] = (facDailyHours[key] || 0) + (s.durationHours || 1);
    if (facDailyHours[key] > 4) {
      violations.push({ type: 'FACULTY_DAILY_LIMIT', message: `Faculty ${s.facultyName} exceeds 4 hours limit on ${s.day}` });
    }
  });

  const hardPenalty = violations.length * 3;
  const score = Math.max(0, 25 - hardPenalty);

  return {
    isClashFree: violations.length === 0,
    totalSessions: sessions.length,
    totalTeachingHours: sessions.reduce((acc, s) => acc + (s.durationHours || 1), 0),
    hardViolationsCount: violations.length,
    violations: violations,
    softPenaltiesCount: softPenalties.length,
    softPenalties: softPenalties,
    correctnessScore: score,
    maxScore: 25,
    timestamp: new Date().toISOString()
  };
}
